#!/usr/bin/env node
// strings-designer.mjs: builds src/InstallerClean.Core/Resources/Strings.Designer.cs
// from the neutral Strings.resx, for regenerate-strings-designer.sh, which writes it,
// and for check-designer-parity.mjs, which compares the committed file with it.
//
// designerFor(resx) returns the whole file: the fixed head below, then one accessor
// for every key the resx defines, in ordinal order of the key, then the closing
// brace. Ordinal, so the file is the same whichever machine and locale build it. The
// accessor is the key with each dot made an underscore, reading the key through Get.
//
// Run from the repo root to write the file: node scripts/strings-designer.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const RESX = 'src/InstallerClean.Core/Resources/Strings.resx';
export const DESIGNER = 'src/InstallerClean.Core/Resources/Strings.Designer.cs';

// Every line before the accessors, as written to the file.
const HEAD = [
  "//------------------------------------------------------------------------------",
  "// <auto-generated>",
  "//     This file is generated by the resx → Designer tooling. Edit Strings.resx",
  "//     and regenerate via scripts/regenerate-strings-designer.sh.",
  "// </auto-generated>",
  "//------------------------------------------------------------------------------",
  "",
  "#nullable enable",
  "",
  "namespace InstallerClean.Resources;",
  "",
  "using System.Resources;",
  "using InstallerClean.Helpers;",
  "",
  "/// <summary>",
  "/// Strongly-typed accessor over Strings.resx. C# code paths use these",
  "/// properties for compile-time safety; XAML uses {loc:Translate Key}",
  "/// (see TranslateExtension) which resolves the same keys at runtime.",
  "/// Get and Find are the only two routes from a resx value to a user and",
  "/// both spend the installer-folder token, which is what lets a string",
  "/// name the cache folder correctly on a machine whose Windows is not on",
  "/// C:. scripts/check-cross-key-rules.mjs fails the build on a third.",
  "/// </summary>",
  "[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"InstallerClean.ResxGen\", \"1.0.0.0\")]",
  "public static class Strings",
  "{",
  "    private static readonly EmbeddedCultureResources Manager =",
  "        new(\"InstallerClean.Resources.Strings\", typeof(Strings).Assembly);",
  "",
  "    /// <summary>",
  "    /// The cached ResourceManager backing every property below, reached",
  "    /// only by the tests that audit the shipped satellites, for the two",
  "    /// things a per-key door cannot do: enumerate a whole resource set,",
  "    /// and answer at a named culture rather than at the UI culture the",
  "    /// app is displaying. The set audits also need the values raw, token",
  "    /// and all.",
  "    /// </summary>",
  "    internal static ResourceManager ResourceManager => Manager;",
  "",
  "    /// <summary>",
  "    /// The door for every key with an accessor below, XAML included",
  "    /// (TranslateExtension calls this), which is why the installer-folder",
  "    /// token is substituted here: a string naming the cache folder is",
  "    /// correct everywhere by writing it. A missing key falls back to the",
  "    /// key itself, so a typo shows on screen rather than as a blank.",
  "    /// </summary>",
  "    internal static string Get(string key) =>",
  "        InstallerFolderToken.Resolve(Manager.GetString(key, Localisation.UiCulture) ?? key);",
  "",
  "    /// <summary>",
  "    /// The door for a key assembled at runtime, which has no accessor",
  "    /// below to come through: the satellite-only plural overrides, built",
  "    /// from a key prefix and a CLDR category. Absent is the ordinary",
  "    /// answer there and means fall back to the neutral form, so this",
  "    /// returns null rather than echoing the key back the way Get does.",
  "    /// </summary>",
  "    internal static string? Find(string key) =>",
  "        Manager.GetString(key, Localisation.UiCulture) is { } value",
  "            ? InstallerFolderToken.Resolve(value)",
  "            : null;",
  "",
];

// The keys the generator reads: a <data name="..."> whose name starts with a letter
// and holds only letters, digits, dots and underscores, each once.
export const designerKeys = (resx) =>
  [...new Set([...resx.matchAll(/<data name="([A-Za-z][A-Za-z0-9._]+)/g)].map((m) => m[1]))]
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

export const designerFor = (resx) =>
  [
    ...HEAD,
    ...designerKeys(resx).map((key) => `    public static string ${key.replaceAll('.', '_')} => Get("${key}");`),
    '}',
    '',
  ].join('\n');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = designerFor(readFileSync(RESX, 'utf8'));
  writeFileSync(DESIGNER, text);
  console.log(`Wrote ${DESIGNER} (${text.split('\n').length - 1} lines)`);
}
